package com.aicontrolcenter.data.backup

import com.aicontrolcenter.core.agents.AgentProfile
import com.aicontrolcenter.core.agents.AgentStats
import com.aicontrolcenter.core.chat.Conversation
import com.aicontrolcenter.core.memory.KnowledgeSpace
import com.aicontrolcenter.core.memory.MemoryLink
import com.aicontrolcenter.core.memory.MemoryRecord
import com.aicontrolcenter.core.registry.AiApp
import com.aicontrolcenter.core.registry.Locality
import com.aicontrolcenter.core.registry.ModelDescriptor
import com.aicontrolcenter.core.registry.ModelProvider
import com.aicontrolcenter.core.registry.ProviderKind
import java.net.URI
import java.net.URISyntaxException
import java.util.Locale

/*
 * Every record of a backup is checked like the owner's own input before it is stored (rule 8: "every record
 * validated like owner input"). The editors' validators live in `:framework` and `:memory` (ProviderDraftValidator,
 * DefaultAgentManager's checks, MemoryRules), which `:data` cannot depend on and which are internal there; the same
 * bounds are applied here, each with the validator it mirrors named, so that a restore stores nothing the app's own
 * editors would refuse. What differs, on purpose:
 * - a cloud Anthropic or Gemini provider without a key is accepted: keys are never in the file (rule 8), the owner
 *   enters them again after restoring;
 * - extra headers are already cut to `HTTP-Referer` and `X-Title` by `BackupRecords.providerForRestore`; they are
 *   then checked as the provider form checks every header.
 * Each check returns what is wrong in plain words for [com.aicontrolcenter.core.backup.BackupProblem.Invalid]
 * ("The backup holds something this app cannot accept (<what>), so nothing was restored."), never the offending text.
 */
object RestoreChecks {
    /** DefaultAgentManager.MAX_NAME_LENGTH. */
    const val AGENT_NAME_CHARS = 40

    /** DefaultAgentManager.MAX_OUTPUT_TOKENS. */
    const val AGENT_MAX_OUTPUT_TOKENS = 200_000

    /** DefaultAgentManager.MAX_RECALL_LIMIT. */
    const val AGENT_MAX_RECALL = 50

    /** DefaultAgentManager.MAX_DELEGATION_DEPTH. */
    const val AGENT_MAX_DELEGATION_DEPTH = 10

    /** ProviderDraftValidator.MAX_NAME_LENGTH. */
    const val PROVIDER_NAME_CHARS = 60

    /** ProviderDraftValidator: at most 20 headers, values of at most 1,000 characters. */
    const val MAX_HEADERS = 20
    const val HEADER_VALUE_CHARS = 1_000

    /** MemoryRules (memory module). */
    const val MEMORY_TITLE_CHARS = 200
    const val MEMORY_CONTENT_CHARS = 20_000
    const val MEMORY_TAGS = 20
    const val MEMORY_TAG_CHARS = 40
    const val SPACE_NAME_CHARS = 80
    const val SPACE_DESCRIPTION_CHARS = 1_000

    /** DefaultAgentChat.MAX_TITLE_LENGTH. */
    const val CHAT_TITLE_CHARS = 80

    /** Ids are generated by the app (`<prefix>_<random>`); a file's ids are bounded and printable. */
    const val ID_CHARS = 200

    /** Model and app names: no editor limit is lower than this for what a provider or a scan reports. Notes have no limit in any editor. */
    const val LABEL_CHARS = 200

    /** The text of one chat entry: as long as a record may be. */
    const val ENTRY_TEXT_CHARS = 4_000_000

    /** The name every validator compares names by: trimmed and case-folded (ProviderDraftValidator.nameKey). */
    fun nameKey(name: String): String = name.trim().uppercase().lowercase()

    fun id(value: String, what: String): String? =
        if (value.isBlank() || value.length > ID_CHARS || value.any { it.isISOControl() || it.isWhitespace() }) "$what with an invalid id" else null

    /** As DefaultAgentManager.validate, with [others] the file's agents before this one. */
    fun agent(agent: AgentProfile, stats: AgentStats, others: Collection<String>): String? {
        id(agent.id.value, "an agent")?.let { return it }
        val name = agent.name.trim()
        return when {
            name.isEmpty() -> "an agent without a name"
            name.length > AGENT_NAME_CHARS -> "an agent name longer than $AGENT_NAME_CHARS characters"
            nameKey(name) in others -> "two agents with the same name"
            agent.generation.temperature?.let { it.isNaN() || it < 0.0 || it > 2.0 } == true -> "an agent temperature outside 0 to 2"
            agent.generation.maxOutputTokens?.let { it !in 1..AGENT_MAX_OUTPUT_TOKENS } == true -> "an agent answer length out of range"
            agent.memory.recallLimit !in 0..AGENT_MAX_RECALL -> "an agent recall limit out of range"
            agent.delegation.maxDepth !in 0..AGENT_MAX_DELEGATION_DEPTH -> "an agent delegation depth out of range"
            agent.modelId?.let { id(it.value, "a model") } != null || agent.fallbackModelIds.any { id(it.value, "a model") != null } ->
                "an agent naming a model with an invalid id"
            agent.toolIds.any { id(it.value, "a tool") != null } -> "an agent naming a tool with an invalid id"
            negative(stats) -> "an agent record with negative counts"
            else -> null
        }
    }

    private fun negative(s: AgentStats): Boolean =
        listOf(
            s.tasksAssigned, s.tasksCompleted, s.tasksFailed, s.tasksTimedOut, s.tasksCancelled, s.reviewsPassed,
            s.revisionsRequested, s.reviewsRejected, s.modelCalls, s.modelErrors, s.toolCalls, s.toolErrors,
        ).any { it < 0 } || s.inputTokens < 0 || s.outputTokens < 0 || s.totalTaskDurationMs < 0

    /**
     * As ProviderDraftValidator.validate for a provider without a key ([provider] as `providerForRestore` left it),
     * with [others] the names of the providers it must not share a name with.
     */
    fun provider(provider: ModelProvider, others: Collection<String>): String? {
        id(provider.id.value, "a provider")?.let { return it }
        if (provider.apiKeyAlias != null) return "a provider that names a key" // providerForRestore clears it; a bug otherwise
        val name = provider.name.trim()
        when {
            name.isEmpty() -> return "a provider without a name"
            name.length > PROVIDER_NAME_CHARS -> return "a provider name longer than $PROVIDER_NAME_CHARS characters"
            nameKey(name) in others -> return "two providers with the same name"
        }
        baseUrlProblem(provider.kind, provider.baseUrl)?.let { return it }
        return headerProblem(provider.extraHeaders)
    }

    private fun runsInProcess(kind: ProviderKind) = kind == ProviderKind.ON_DEVICE || kind == ProviderKind.SIMULATOR

    /** ProviderDraftValidator.baseUrlProblem. */
    private fun baseUrlProblem(kind: ProviderKind, raw: String?): String? {
        val url = raw?.trim()?.trimEnd('/')?.ifEmpty { null }
        if (url == null) {
            val required = kind == ProviderKind.OPENAI_COMPATIBLE || kind == ProviderKind.OLLAMA
            return if (required) "a provider without an address" else null
        }
        if (runsInProcess(kind)) return "a built-in provider with an address"
        val uri = try {
            URI(url)
        } catch (_: URISyntaxException) {
            return "a provider with an invalid address"
        }
        val scheme = uri.scheme?.lowercase()
        return when {
            scheme != "http" && scheme != "https" -> "a provider address that is not http or https"
            uri.host.isNullOrEmpty() -> "a provider address without a host"
            uri.rawUserInfo != null -> "a provider address holding a user name or password"
            uri.rawQuery != null || uri.rawFragment != null -> "a provider address with a \"?\" or \"#\" part"
            uri.port == 0 || uri.port > 65_535 -> "a provider address with an invalid port"
            scheme == "http" && Locality.infer(kind, url) == Locality.CLOUD -> "a provider on the internet reached over plain http"
            else -> null
        }
    }

    /** RFC 9110 "token": the characters allowed in a header name (ProviderDraftValidator). */
    private val HEADER_NAME = Regex("[A-Za-z0-9!#$%&'*+.^_`|~-]+")

    /** ProviderDraftValidator.headerProblems, for the headers a file may hold. */
    private fun headerProblem(headers: Map<String, String>): String? {
        if (headers.size > MAX_HEADERS) return "a provider with too many extra headers"
        val seen = HashSet<String>()
        for ((rawName, value) in headers) {
            val name = rawName.trim()
            when {
                !HEADER_NAME.matches(name) -> return "a provider header with an invalid name"
                !seen.add(name.lowercase(Locale.ROOT)) -> return "a provider header listed twice"
                value.length > HEADER_VALUE_CHARS -> return "a provider header value that is too long"
                value.any { it != '\t' && (it < ' ' || it > '~') } -> return "a provider header value with characters not allowed in a header"
            }
        }
        return null
    }

    fun model(model: ModelDescriptor): String? {
        id(model.id.value, "a model")?.let { return it }
        id(model.providerId.value, "a model's provider")?.let { return it }
        return when {
            model.modelName.isBlank() || model.modelName.length > LABEL_CHARS -> "a model without a valid name"
            model.displayName.length > LABEL_CHARS -> "a model with a display name that is too long"
            model.sizeBytes?.let { it < 0 } == true -> "a model with a negative size"
            model.capabilities.contextWindow?.let { it < 0 } == true || model.capabilities.maxOutputTokens?.let { it < 0 } == true ->
                "a model with negative limits"
            else -> null
        }
    }

    /**
     * An AI app's entry is mostly what a scan of the phone found (its label, vendor and version as Android reports them),
     * so only what the app acts on is held to a rule: the package name it opens and the web link it fills a prompt into.
     */
    fun aiApp(app: AiApp): String? {
        id(app.id.value, "an AI app")?.let { return it }
        return when {
            !PACKAGE_NAME.matches(app.packageName) -> "an AI app with an invalid package name"
            app.label.length > LABEL_CHARS -> "an AI app with a name that is too long"
            (app.vendor?.length ?: 0) > LABEL_CHARS || (app.versionName?.length ?: 0) > LABEL_CHARS -> "an AI app with a name that is too long"
            app.promptDeepLink?.let { !it.startsWith("https://") || it.length > 2_000 } == true -> "an AI app with an invalid web link"
            app.linkedProviderId?.let { id(it.value, "a provider") } != null -> "an AI app naming a provider with an invalid id"
            else -> null
        }
    }

    /** An Android package name: dot-separated Java identifiers, at least two segments. */
    private val PACKAGE_NAME = Regex("[A-Za-z][A-Za-z0-9_]*(\\.[A-Za-z][A-Za-z0-9_]*)+")

    /** The key two spaces' names are compared by (KnowledgeSpaces.requireUniqueName). */
    fun spaceNameKey(name: String): String = name.trim().lowercase(Locale.ROOT)

    /** MemoryRules.spaceName and spaceDescription, and no two spaces of one name; [others] are the keys of the file's spaces before it. */
    fun space(space: KnowledgeSpace, others: Collection<String>): String? {
        id(space.id.value, "a space")?.let { return it }
        val name = space.name.trim()
        return when {
            name.isEmpty() -> "a space without a name"
            name.length > SPACE_NAME_CHARS -> "a space name longer than $SPACE_NAME_CHARS characters"
            spaceNameKey(name) in others -> "two spaces with the same name"
            space.description.trim().length > SPACE_DESCRIPTION_CHARS -> "a space description that is too long"
            else -> null
        }
    }

    /** MemoryRules (title, content, tags, unit values, lifetime). */
    fun memory(memory: MemoryRecord): String? {
        id(memory.id.value, "a memory")?.let { return it }
        val title = memory.title.trim()
        val content = memory.content.trim()
        return when {
            title.isEmpty() || title.length > MEMORY_TITLE_CHARS -> "a memory without a valid title"
            content.isEmpty() || content.length > MEMORY_CONTENT_CHARS -> "a memory without valid content"
            memory.tags.size > MEMORY_TAGS || memory.tags.any { it.isBlank() || it.length > MEMORY_TAG_CHARS } -> "a memory with invalid tags"
            !unit(memory.importance) || !unit(memory.confidence) -> "a memory with a value outside 0 to 1"
            memory.expiresAt?.let { it <= 0 } == true -> "a memory with an invalid lifetime"
            memory.revision < 1 || memory.accessCount < 0 -> "a memory with invalid counts"
            else -> null
        }
    }

    fun link(link: MemoryLink): String? {
        id(link.id.value, "a memory link")?.let { return it }
        return if (!unit(link.weight)) "a memory link with a weight outside 0 to 1" else null
    }

    fun conversation(conversation: Conversation): String? {
        id(conversation.id.value, "a chat")?.let { return it }
        return if (conversation.title.length > CHAT_TITLE_CHARS) "a chat title longer than $CHAT_TITLE_CHARS characters" else null
    }

    fun entryText(text: String): String? = if (text.isBlank() || text.length > ENTRY_TEXT_CHARS) "a chat message without valid text" else null

    private fun unit(value: Double) = value.isFinite() && value in 0.0..1.0
}
